"""Run the tiny Qwen3 firmware through the REAL merged Qwen3.5-4B checkpoint (stock Qwen3_5ForCausalLM chip layers, HF modules).

python hfcheck.py MODEL_DIR q3.elf [--steps N]    (from <qwenputer npu>/experimental/riscv, .venv python)
Teacher-forced by the reference trace (as chipformer.rv.npucheck): the circuit's prediction at every position must be the next
trace token. The model owns every generated byte; here prediction == reference trace is the exactness criterion.
"""
import argparse, json, time, sys
from chipformer.rv import elf, ref
from chipformer.rv.chat import RvChat
from chipformer.rv.npucheck import check

ap = argparse.ArgumentParser(); ap.add_argument("model"); ap.add_argument("elf"); ap.add_argument("--steps", type=int, default=45000)
a = ap.parse_args()
chat = RvChat(a.model)
prog = elf.program(a.elf)
t = time.time(); r = check(chat, prog, a.steps); r["wall_s"] = round(time.time() - t, 1)
r["trace_tokens_per_s"] = round(r["steps"] / r["seconds"], 1)
print(json.dumps(r)); sys.exit(0 if r["mismatch"] is None else 1)
